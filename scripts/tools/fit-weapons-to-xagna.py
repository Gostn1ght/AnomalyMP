"""Fit GAMMA's weapons to the xAGNA hand poses (owner 2026-10-13, doc 101).

xAGNA (doc 90) replaced the player and NPC weapon motions; its
mod_system_zzzzzzzzzz_xagna_wpn_pos.ltx places 189 weapons in those hands.
The rest of GAMMA's weapons kept offsets made for the old motions and float
above the hands (players and NPCs). Each of them takes the orientation and
side/forward offsets of the most similar weapon xAGNA placed (same animation
slot and class, nearest barrel length and inventory width), and keeps its own
height, which belongs to its model's origin. Writes the DLTX file loaded right
after xAGNA's.

    python scripts/tools/fit-weapons-to-xagna.py <client configs dir> <out.ltx>

The output goes to client/ and server/configs of the overlay as
mod_system_zzzzzzzzzzzzzzzzzzzz_lostzone_wpn_fit.ltx (loaded after every
GAMMA file, so these values are the final ones).
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import ltx_resolve as dltx  # noqa: E402

XAGNA = "mod_system_zzzzzzzzzz_xagna_wpn_pos.ltx"
SLOTS = {"2", "3", "8", "9", "10"}


def fmt(v):
    return ", ".join(("%.6f" % a).rstrip("0").rstrip(".") if a else "0" for a in v)


def main(root, out):
    root = Path(root)
    new = dltx.Ltx().load_system(root)
    old = dltx.Ltx().load_system(root, skip_mods=(XAGNA,))
    xagna = set(re.findall(r"^!\[([^\]]+)\]", (root / XAGNA).read_text(encoding="cp1251"), re.M))

    def features(sec):
        fp = dltx.vec(new.get(sec, "fire_point")) or [0, 0, 0.5]
        ammo = (new.get(sec, "ammo_class") or "").split(",")[0].strip()
        return {"slot": new.get(sec, "animation_slot"), "class": new.get(sec, "class"),
                "barrel": fp[2], "grid": float(new.get(sec, "inv_grid_width") or 5),
                # submachine guns (pistol rounds) and shotguns sit in the hands unlike rifles
                "kind": "smg" if re.match(r"ammo_(9x18|9x19|11\.43|5\.7x28|7\.62x25|4\.6x30|10x25|357|45)", ammo)
                else "shotgun" if re.match(r"ammo_(12x|20x|23x|410)", ammo) else "rifle"}

    # xAGNA's placements whose height matches GAMMA's model: those are the
    # same models (a large height change means xAGNA had another model).
    refs = []
    for sec in xagna:
        o_pos, n_pos = dltx.vec(old.get(sec, "position")), dltx.vec(new.get(sec, "position"))
        n_ori = dltx.vec(new.get(sec, "orientation"))
        if not (o_pos and n_pos and n_ori) or new.get(sec, "animation_slot") not in SLOTS:
            continue
        # Same height: the same model as GAMMA's. Another height: xAGNA had
        # another model - its pose still serves the weapon's own family.
        refs.append((sec, features(sec), o_pos, n_pos, n_ori, abs(n_pos[1] - o_pos[1]) <= 0.03))

    def family(sec, ref):
        # wpn_vintorez_n1 is a vintorez: the longest name xAGNA placed that
        # this one starts with ("wpn_" alone does not count).
        name = ref[0]
        return len(name) if sec == name or sec.startswith(name + "_") else 0

    def nearest(sec, f):
        best = max(refs, key=lambda ref: family(sec, ref))
        if family(sec, best):
            return best
        def cost(ref):
            g = ref[1]
            return ((0 if g["slot"] == f["slot"] else 10) + (0 if g["class"] == f["class"] else 2)
                    + (0 if g["kind"] == f["kind"] else 6)
                    + abs(g["barrel"] - f["barrel"]) * 8 + abs(g["grid"] - f["grid"]) * 2)
        return min((ref for ref in refs if ref[5]), key=cost)

    lines = [
        "; Lost Zone (doc 101): GAMMA weapons xAGNA did not place, fitted to the xAGNA hand",
        "; poses from the most similar weapon it did place; generated by",
        "; scripts/tools/fit-weapons-to-xagna.py - do not edit by hand.",
    ]
    count = 0
    # xAGNA placed these for another model than GAMMA's (heights 8-24 cm
    # apart): its pose stays, the height is GAMMA's model's.
    for ref in sorted(refs):
        sec, _, o_pos, n_pos, n_ori, same_model = ref
        if same_model or new.get(sec, "class") in ("WP_KNIFE", "WP_BINOC"):
            continue
        if dltx.vec(new.get(sec, "position")) != n_pos:
            continue  # a later GAMMA file placed it already
        lines += ["", "![%s] ; xAGNA pose, GAMMA model height" % sec,
                  "        position                         = " + fmt([n_pos[0], o_pos[1], n_pos[2]])]
        count += 1
    for sec in sorted(new.raw):
        if not sec.startswith("wpn_") or sec.endswith("_hud") or sec in xagna:
            continue
        if new.get(sec, "visual") is None or new.get(sec, "animation_slot") not in SLOTS:
            continue
        if new.get(sec, "class") in ("WP_KNIFE", "WP_BINOC") or "_axe" in sec:
            continue  # axes: melee grip (ActorAnimation.cpp), not a rifle's
        if not new.own(sec, "position") and not new.own(sec, "orientation"):
            continue  # inherits its placement from the weapon it is based on
        pos, ori = dltx.vec(new.get(sec, "position")), dltx.vec(new.get(sec, "orientation"))
        if not (pos and ori) or pos != dltx.vec(old.get(sec, "position")):
            continue
        ref_sec, _, ref_old, ref_new, ref_ori, same_model = nearest(sec, features(sec))
        fitted = [ref_new[0], pos[1] + (ref_new[1] - ref_old[1] if same_model else 0), ref_new[2]]
        lines += ["", "![%s] ; like %s" % (sec, ref_sec),
                  "        position                         = " + fmt(fitted),
                  "        orientation                      = " + fmt(ref_ori)]
        count += 1
    Path(out).write_bytes(("\r\n".join(lines) + "\r\n").encode("cp1251"))
    print(count, "weapons fitted from", len(refs), "xAGNA placements ->", out)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
